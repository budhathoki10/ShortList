import { mkdirSync, readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";
import { FIXTURE_BASE } from "../playwright.config";
import { addFixtureJob, setUpJobSeeker, signUp } from "./helpers";

test("short answers get useful coaching and email drafts use the current letter", async ({ page }) => {
  const email = `coaching-${Date.now()}@example.com`;
  await setUpJobSeeker(page, email);
  const jobUrl = await addFixtureJob(page, FIXTURE_BASE);
  await page.goto(`${jobUrl}/interview`);
  await expect(page.getByRole("button", { name: "Start mock interview", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Get my questions" }).click();
  const question = page.getByRole("region", { name: "Current interview question" });
  await expect(question.getByText("How to approach this answer")).toBeVisible();
  await question.getByLabel("Your answer", { exact: true }).fill("I can help customers use Zendesk.");
  await question.getByRole("button", { name: "Get feedback", exact: true }).click();
  const feedback = page.getByLabel("Answer feedback");
  await expect(feedback).toBeVisible();
  await expect(feedback).toContainText("Guided practice · unscored");
  await expect(feedback.getByRole("heading", { name: "Fix this first" })).toBeVisible();
  await expect(feedback.getByRole("heading", { name: "An example to learn from" })).toBeVisible();
  await expect(feedback).toContainText("[Explain your own contribution");
  await expect(feedback.locator("details")).not.toHaveAttribute("open");
  mkdirSync("tmp/cv-audit/ui", { recursive: true });
  await page.screenshot({ path: "tmp/cv-audit/ui/coaching-feedback-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "tmp/cv-audit/ui/coaching-feedback-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  await question.getByLabel("Your answer", { exact: true }).fill("I built a new answer.");
  await expect(page.getByText("You’ve changed your answer.")).toBeVisible();
  await expect(feedback).toBeHidden();
  await page.getByRole("button", { name: "Next question" }).click();
  await page.getByRole("button", { name: "Previous" }).click();
  await expect(page.getByLabel("Your answer", { exact: true })).toHaveValue("I built a new answer.");

  mkdirSync("tmp/cv-audit/ui", { recursive: true });
  await page.screenshot({ path: "tmp/cv-audit/ui/interview-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "interview fits phone").toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "tmp/cv-audit/ui/interview-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole("button", { name: "Refresh practice questions" }).click();
  await expect(page.getByText(/\d+ questions to practise\./)).toBeVisible();
  await page.locator("summary").filter({ hasText: /^Saved earlier practice ·/ }).click();
  await expect(page.getByText("I can help customers use Zendesk.", { exact: true })).toBeVisible();
  await page.getByRole("navigation", { name: "Interview mode" }).getByRole("link", { name: "Mock interview", exact: true }).click();
  await expect(page.getByRole("region", { name: "Current interview question" })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Mock interview", exact: true })).toBeVisible();
  await page.getByRole("navigation", { name: "Interview mode" }).getByRole("link", { name: "Question practice", exact: true }).click();
  await expect(page.getByRole("region", { name: "Current interview question" })).toBeVisible();
  await page.goto(`${jobUrl}/cover-letter`);
  await page.getByRole("button", { name: "Write a draft" }).click();
  await page.getByLabel("Cover letter", { exact: true }).fill("Dear hiring team,\n\nI built a customer onboarding workflow.\n\nThank you.");
  await page.getByLabel("Company email").fill("hiring@example.com");
  const gmail = new URL((await page.getByRole("link", { name: "Open in Gmail" }).getAttribute("href"))!);
  expect(gmail.searchParams.get("authuser")).toBe(email);
  expect(gmail.searchParams.get("body")).toContain("I built a customer onboarding workflow.");
  expect(gmail.searchParams.get("to")).toBe("hiring@example.com");
  await page.screenshot({ path: "tmp/cv-audit/ui/cover-desktop.png", fullPage: true });
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `cover letter fits ${width}px`).toBe(true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "tmp/cv-audit/ui/cover-mobile.png", fullPage: true });
});

test("the supplied original CV survives upload, editing and PDF download", async ({ page }) => {
  mkdirSync("tmp/cv-audit/ui", { recursive: true });
  const file = process.env.CV_QUALITY_FILE;
  test.skip(!file, "Set CV_QUALITY_FILE to verify the supplied original CV locally.");
  const email = `cv-quality-${Date.now()}@example.com`;
  await signUp(page, email);
  await page.locator("input[type=file][name=file]").setInputFiles(file!);
  await page.getByRole("button", { name: "Read my CV" }).click();
  await expect(page.getByLabel("Full name")).toHaveValue("KUSHAL BUDHATHOKI");
  await expect(page.getByLabel("Links", { exact: true })).toHaveValue(/linkedin\.com.*\ngithub|linkedin\.com[\s\S]*github\.com/);
  await page.screenshot({ path: "tmp/cv-audit/ui/profile-desktop.png", fullPage: true });
  await page.getByRole("navigation", { name: "CV sections" }).getByRole("button", { name: /Projects/ }).click();
  await expect(page.getByLabel("Project title", { exact: true })).toHaveCount(3);
  const links = await page.getByLabel("Project URL", { exact: true }).evaluateAll((els) => els.map((el) => (el as HTMLInputElement).value));
  expect(links).toEqual(["https://autopilot.kushalbudhathoki.com.np/", "https://codereview.kushalbudhathoki.com.np/", "https://feedwatch.kushalbudhathoki.com.np/"]);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "tmp/cv-audit/ui/projects-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "tmp/cv-audit/ui/projects-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole("button", { name: "Save profile", exact: true }).click();
  await expect(page.getByText("Profile saved.")).toBeVisible();
  const jobUrl = await addFixtureJob(page, FIXTURE_BASE);
  const pdf = await page.request.get(`${jobUrl.replace("/app/jobs/", "/app/download/cv/")}?format=pdf`);
  expect(pdf.status()).toBe(200);
  expect(pdf.headers()["content-type"]).toBe("application/pdf");
  expect((await pdf.body()).subarray(0, 4).toString()).toBe("%PDF");
  expect(await pdf.body()).toEqual(readFileSync(file!));
  const sourcePdf = await page.request.get("/app/download/profile");
  expect(sourcePdf.status()).toBe(200);
  expect(sourcePdf.headers()["content-type"]).toBe("application/pdf");
  expect(await sourcePdf.body()).toEqual(readFileSync(file!));
  const originalPdf = await page.request.get("/app/download/original?inline=1");
  expect(await originalPdf.body()).toEqual(readFileSync(file!));
  expect(originalPdf.headers()["content-disposition"]).toContain("inline;");
  const redesigned = await page.request.get(`${jobUrl.replace("/app/jobs/", "/app/download/cv/")}?format=pdf&layout=redesigned`);
  expect(redesigned.status()).toBe(200);
  expect((await redesigned.body()).equals(readFileSync(file!))).toBe(false);
  await page.goto(`${jobUrl}/cv`);
  await page.getByRole("button", { name: "Suggest changes", exact: true }).click();
  await expect(page.getByRole("button", { name: "Tailored version", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("link", { name: "Download PDF", exact: true })).toHaveAttribute("href", /layout=redesigned/);
  await page.getByRole("button", { name: "Original PDF", exact: true }).click();
  await expect(page.getByText("Your uploaded PDF, unchanged")).toBeVisible();
  await expect(page.getByRole("link", { name: "Download PDF", exact: true })).toHaveAttribute("href", /layout=original/);
  const originalPreview = page.getByRole("img", { name: "Original PDF page 1 of 3", exact: true });
  await expect(originalPreview).toHaveAttribute("data-rendered", "true");
  expect(await originalPreview.evaluate((el) => {
    const canvas = el as HTMLCanvasElement;
    const pixels = canvas.getContext("2d")!.getImageData(0, 0, canvas.width, canvas.height).data;
    let dark = 0;
    for (let i = 0; i < pixels.length; i += 4) if (pixels[i] < 100 && pixels[i + 3] > 0) dark++;
    return dark;
  })).toBeGreaterThan(1000);
  await page.screenshot({ path: "tmp/cv-audit/ui/original-format-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "tmp/cv-audit/ui/original-format-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Tailored version", exact: true }).click();
  await expect(page.getByRole("button", { name: "Full source", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("link", { name: "Download PDF", exact: true })).toHaveAttribute("href", /layout=redesigned/);
  await page.goto("/app/profile");
  await expect(page.getByRole("link", { name: "Download original PDF", exact: true })).toBeVisible();
  for (const width of [320, 390, 768, 1280, 1600]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `profile fits ${width}px`).toBe(true);
    await expect(page.getByRole("button", { name: "Save profile" })).toBeVisible();
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "tmp/cv-audit/ui/profile-mobile.png", fullPage: true });
});
